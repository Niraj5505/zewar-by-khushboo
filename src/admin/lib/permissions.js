export const ROLES = {
  SUPER_ADMIN: 'SUPER_ADMIN',
  ADMIN: 'ADMIN',
  STAFF: 'STAFF',
};

export const PERMISSIONS = {
  // Catalog
  VIEW_PRODUCTS: [ROLES.SUPER_ADMIN, ROLES.ADMIN, ROLES.STAFF],
  EDIT_PRODUCTS: [ROLES.SUPER_ADMIN, ROLES.ADMIN],
  DELETE_PRODUCTS: [ROLES.SUPER_ADMIN, ROLES.ADMIN],
  EDIT_PRICING: [ROLES.SUPER_ADMIN, ROLES.ADMIN],
  EDIT_INVENTORY: [ROLES.SUPER_ADMIN, ROLES.ADMIN, ROLES.STAFF],

  // Orders
  VIEW_ORDERS: [ROLES.SUPER_ADMIN, ROLES.ADMIN, ROLES.STAFF],
  UPDATE_FULFILLMENT: [ROLES.SUPER_ADMIN, ROLES.ADMIN, ROLES.STAFF],
  CANCEL_ORDERS: [ROLES.SUPER_ADMIN, ROLES.ADMIN],
  ISSUE_REFUNDS: [ROLES.SUPER_ADMIN, ROLES.ADMIN],

  // Customers & Reviews
  VIEW_CUSTOMERS: [ROLES.SUPER_ADMIN, ROLES.ADMIN, ROLES.STAFF],
  EXPORT_CUSTOMERS: [ROLES.SUPER_ADMIN, ROLES.ADMIN],
  MODERATE_REVIEWS: [ROLES.SUPER_ADMIN, ROLES.ADMIN, ROLES.STAFF],

  // Marketing & Content
  MANAGE_MARKETING: [ROLES.SUPER_ADMIN, ROLES.ADMIN],
  MANAGE_CONTENT: [ROLES.SUPER_ADMIN, ROLES.ADMIN],

  // Shipping
  MANAGE_SHIPPING: [ROLES.SUPER_ADMIN, ROLES.ADMIN],

  // Settings
  MANAGE_STORE_SETTINGS: [ROLES.SUPER_ADMIN, ROLES.ADMIN],
  MANAGE_PAYMENTS: [ROLES.SUPER_ADMIN],
  MANAGE_USERS: [ROLES.SUPER_ADMIN],
  VIEW_AUDIT_LOGS: [ROLES.SUPER_ADMIN, ROLES.ADMIN],

  // Reports
  VIEW_REPORTS: [ROLES.SUPER_ADMIN, ROLES.ADMIN],
};

export const hasPermission = (userRole, permissionKey) => {
  if (!userRole) return false;
  const allowed = PERMISSIONS[permissionKey];
  return allowed ? allowed.includes(userRole) : false;
};
